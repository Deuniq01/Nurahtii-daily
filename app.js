async function adminReset(){
  if(!confirm('Permanently delete all app data from this browser and every document in the Firebase userData collection? This cannot be undone.'))return;
  const button=document.getElementById('adminResetButton');
  button.disabled=true;
  button.textContent='Clearing...';
  try{
    await firebaseWriteQueue;
    await deleteFirebaseData();
  }catch(error){
    const details=error instanceof Error?error.message:String(error);
    alert('Firebase data could not be fully cleared. Browser data was left intact; cloud deletion may be partial. Check Firebase permissions and retry. Details: '+details);
    return;
  }finally{
    button.disabled=false;
    button.textContent='Reset All Data';
  }
  Object.keys(localStorage).filter(k=>k.startsWith('nur_')).forEach(k=>localStorage.removeItem(k));
  setSyncWarning(false);
  showPage('pg-entry');
}

async function deleteFirebaseData(){
  const db=await getDB();
  const {collection,getDocs,limit,query,writeBatch}=await import("https://www.gstatic.com/firebasejs/10.12.0/firebase-firestore.js");
  while(true){
    const snapshot=await getDocs(query(collection(db,'userData'),limit(450)));
    if(snapshot.empty)return;
    const batch=writeBatch(db);
    snapshot.docs.forEach(item=>batch.delete(item.ref));
    await batch.commit();
  }
}

