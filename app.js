let cdInterval,cdActive=0;

function getAnnualEventDate(event,now){
  const today=new Date(now.getFullYear(),now.getMonth(),now.getDate());
  const date=new Date(now.getFullYear(),event.month-1,event.day);
  if(date<today)date.setFullYear(date.getFullYear()+1);
  return date;
}

function switchCD(i){
  cdActive=i;
  document.querySelectorAll('.cd-tab').forEach((t,j)=>t.classList.toggle('active',j===i));
  startCountdown();
}

function startCountdown(){
  if(cdInterval)clearInterval(cdInterval);
  const ev=CD_EVENTS[cdActive];
  const target=document.getElementById('cdTarget');
  const sub=document.getElementById('cdSub');
  let eventDate=null;
  function update(){
    const now=new Date();
    const nextDate=getAnnualEventDate(ev,now);
    if(!eventDate||nextDate.getTime()!==eventDate.getTime()){
      eventDate=nextDate;
      target.textContent=ev.icon+' '+ev.label+' — '+eventDate.toLocaleDateString(undefined,{month:'long',day:'numeric',year:'numeric'});
    }
    if(now.getMonth()+1===ev.month&&now.getDate()===ev.day){
      ['cdDays','cdHours','cdMins','cdSecs'].forEach(id=>document.getElementById(id).textContent='00');
      sub.textContent='🎉 The day has arrived! Celebrate well. ✨';
      return;
    }
    sub.textContent=ev.sub;
    const diff=eventDate-now;
    document.getElementById('cdDays').textContent=String(Math.floor(diff/(864e5))).padStart(2,'0');
    document.getElementById('cdHours').textContent=String(Math.floor((diff%864e5)/36e5)).padStart(2,'0');
    document.getElementById('cdMins').textContent=String(Math.floor((diff%36e5)/6e4)).padStart(2,'0');
    document.getElementById('cdSecs').textContent=String(Math.floor((diff%6e4)/1e3)).padStart(2,'0');
  }
  update();cdInterval=setInterval(update,1000);
}

