const PENDING_WRITES_KEY='pendingWrites';
const PLANNED_CONTENT_HORIZON=730;
const MAX_CONTENT_DAY=10000;
let firebaseWriteQueue=Promise.resolve();
let firebaseWriteSequence=0;

function getPendingWrites(){
  const stored=localStorage.getItem('nur_'+PENDING_WRITES_KEY);
  if(stored===null)return {};
  let pending;
  try{
    pending=JSON.parse(stored);
  }catch(error){
    console.error('Pending Firebase write queue could not be read:',error);
    setSyncWarning(true,'A saved cloud change could not be read. Your local data was not cleared; retry sync or contact the site owner.');
    throw new Error('Pending Firebase write queue is invalid.');
  }
  if(!pending||typeof pending!=='object'||Array.isArray(pending)){
    const error=new Error('Pending Firebase write queue has an invalid format.');
    console.error(error);
    setSyncWarning(true,'A saved cloud change could not be read. Your local data was not cleared; retry sync or contact the site owner.');
    throw error;
  }
  return pending;
}

function hasPendingWrites(){
  return Object.keys(getPendingWrites()).length>0;
}

function queueFirebaseWrite(key,value,token){
  const operation=firebaseWriteQueue.then(async()=>{
    await fbSet(key,value);
    CACHE.set(key,value);
    const pending=getPendingWrites();
    if(pending[key]?.token===token){
      delete pending[key];
      CACHE.set(PENDING_WRITES_KEY,pending);
    }
  });
  firebaseWriteQueue=operation.catch(()=>{});
  return operation;
}

async function flushPendingWrites(){
  const pending=getPendingWrites();
  for(const [key,record] of Object.entries(pending)){
    if(!record||typeof record!=='object'||!Object.prototype.hasOwnProperty.call(record,'value')||typeof record.token!=='string'){
      throw new Error(`Invalid pending Firebase write for ${key}`);
    }
    await queueFirebaseWrite(key,record.value,record.token);
  }
}

const STORE = {
  get:(k)=>CACHE.get(k),
  set:async(k,v)=>{
    CACHE.set(k,v);
    const token=`${Date.now()}-${++firebaseWriteSequence}`;
    const pending=getPendingWrites();
    pending[k]={value:v,token};
    CACHE.set(PENDING_WRITES_KEY,pending);
    try{
      await queueFirebaseWrite(k,v,token);
      return true;
    }catch(error){
      console.error(`Firebase write failed for ${k}; the local change is queued for retry:`,error);
      setSyncWarning(true,'Changes are saved on this device and will sync when Firebase is available.');
      return false;
    }
  }
};

/* On load: pull all saved data from Firebase into localStorage */
async function syncFromFirebase() {
  await flushPendingWrites();
  const keys = ['startDate','moodHistory','jarOpened','dqAnswers','qaList','jarExtras'];
  const values=await Promise.all(keys.map(key=>fbGet(key)));
  const startDate=values[0]!==null?values[0]:CACHE.get('startDate');
  const day=getDayFrom(startDate);
  const nearbyDays=[];
  for(let nearbyDay=Math.max(1,day-2);nearbyDay<=day+2;nearbyDay++)nearbyDays.push(nearbyDay);
  const extraKeys=nearbyDays.flatMap(nearbyDay=>[`noteOverride_${nearbyDay}`,`contentDay_${nearbyDay}`]);
  const extraValues=await Promise.all(extraKeys.map(key=>fbGet(key)));
  [...keys,...extraKeys].forEach((key,index)=>{
    const value=index<keys.length?values[index]:extraValues[index-keys.length];
    if(value!==null)CACHE.set(key,value);
  });
}

