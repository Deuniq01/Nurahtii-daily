function getDayFrom(start){
  if(!start) start=new Date().toISOString().split('T')[0];
  const startTime=new Date(start).getTime();
  if(!Number.isFinite(startTime))throw new Error('The saved start date is invalid.');
  return Math.max(1,Math.floor((Date.now()-startTime)/(1000*60*60*24))+1);
}
